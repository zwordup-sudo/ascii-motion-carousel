import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, mkdirSync, copyFileSync, writeFileSync, readFileSync, readdirSync, rmSync, appendFileSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
import assert from 'node:assert/strict';
const kit = resolve(import.meta.dirname, '..');
const source = join(kit, '.deving', 'quality');
const root = mkdtempSync(join(tmpdir(), 'deving-quality-test-'));
function tool(...args) {return spawnSync(process.execPath, args,{cwd:root,encoding:'utf8',timeout:120000});}
try {
  mkdirSync(join(root,'.deving','quality'),{recursive:true});
  mkdirSync(join(root,'.deving','evidence'),{recursive:true});
  mkdirSync(join(root,'fixtures'),{recursive:true});
  copyFileSync(join(source,'engine.mjs'),join(root,'.deving','quality','engine.mjs'));
  copyFileSync(join(source,'config.json'),join(root,'.deving','quality','config.json'));
  writeFileSync(join(root,'.deving','evidence','.gitignore'),'*\n!.gitignore\n');
  writeFileSync(join(root,'.gitignore'),'.deving/evidence/*\n');
  writeFileSync(join(root,'fixtures','unit.mjs'), `import fs from 'node:fs';
const arg=process.argv.find(x=>x.startsWith('--outputFile='));
if(arg) fs.writeFileSync(arg.slice('--outputFile='.length), JSON.stringify({numTotalTests:110,numPassedTests:110,numFailedTests:0,numPendingTests:0,numTodoTests:0}));
console.log('Test Files 10 passed\\nTests 110 passed');
`);
  writeFileSync(join(root,'fixtures','build.mjs'),"console.log('built 40 modules')\n");
  writeFileSync(join(root,'fixtures','e2e.mjs'),"console.log('126 passed (3.2m)\\n3 skipped')\n");
  writeFileSync(join(root,'package.json'),JSON.stringify({name:'deving-fixture',version:'1.0.0',scripts:{test:'node fixtures/unit.mjs',build:'node fixtures/build.mjs','test:e2e':'node fixtures/e2e.mjs'}},null,2));
  execFileSync('git',['init','-q'],{cwd:root});
  execFileSync('git',['config','user.email','ci@example.invalid'],{cwd:root});
  execFileSync('git',['config','user.name','Local CI'],{cwd:root});
  execFileSync('git',['add','fixtures','package.json','.gitignore'],{cwd:root});
  execFileSync('git',['commit','-qm','fixture'],{cwd:root});
  const args=['.deving/quality/engine.mjs'];
  let r=tool(...args,'plan');
  assert.equal(r.status,0,r.stderr);
  assert.match(r.stdout,/COMPATIBLE/);
  assert.equal(readdirSync(join(root,'.deving','evidence')).filter(x=>x!=='.gitignore').length,0,'Plan should not generate evidence');
  r=tool(...args,'run');
  assert.equal(r.status,0,r.stderr+'\n'+r.stdout);
  assert.match(r.stdout,/VALIDADO_DESARROLLO/);
  let runs=readdirSync(join(root,'.deving','evidence')).filter(x=>x!=='.gitignore');
  assert.equal(runs.length,1);
  let dir=join(root,'.deving','evidence',runs[0]);
  let data=JSON.parse(readFileSync(join(dir,'manifest.json'),'utf8'));
  assert.equal(data.checks.length,3);
  assert.deepEqual(data.checks.map(c=>c.status),['pass','pass','pass']);
  assert.equal(data.checks[2].skips,3);
  assert.equal(data.checks[0].passed_count,110);
  assert.equal(data.checks[0].skips,0);
  assert.equal(data.checks[0].result_json,'unit-results.json');
  assert.ok(data.checks[0].result_sha256);
  assert.ok(data.git.before.untracked_count>=2);
  assert.equal(data.checks[2].passed_count,126);
  assert.equal(data.git.unchanged,true);
  r=tool(...args,'verify','--report',dir);
  assert.equal(r.status,0,r.stderr+' '+r.stdout);
  assert.match(r.stdout,/CONCUERDAN/);
  const unitLog = join(dir,'unit.log');
  const oldUnitLog = readFileSync(unitLog);
  appendFileSync(unitLog,'\nTAMPER\n');
  r=tool(...args,'verify','--report',dir);
  assert.equal(r.status,2,'Verify must catch tampered log');
  writeFileSync(unitLog,oldUnitLog);
  r=tool(...args,'verify','--report',dir);
  assert.equal(r.status,0,'Verify restored log');
  const unitJson = join(dir,'unit-results.json');
  const oldJson = readFileSync(unitJson);
  appendFileSync(unitJson,'\nTAMPER\n');
  r=tool(...args,'verify','--report',dir);
  assert.equal(r.status,2,'Verify detects modified unit JSON');
  writeFileSync(unitJson,oldJson);
  r=tool(...args,'verify','--report',dir);
  assert.equal(r.status,0,'Verify restored unit JSON');
  // JSON absent with exit 0 must not count as unit PASS.
  const unitFixture=join(root,'fixtures','unit.mjs');
  const unitFixtureOld=readFileSync(unitFixture);
  writeFileSync(unitFixture,"console.log('Tests 110 passed')\n");
  r=tool(...args,'run');
  assert.equal(r.status,1,r.stderr);
  assert.match(r.stdout,/VALIDACION_INCOMPLETA/);
  writeFileSync(unitFixture,unitFixtureOld);
  r=tool(...args,'run','--production');
  assert.equal(r.status,0,r.stderr+'\n'+r.stdout);
  assert.match(r.stdout,/VALIDADO_E2E_PRODUCCION_LOCAL/);
  runs=readdirSync(join(root,'.deving','evidence')).filter(x=>x!=='.gitignore');
  assert.equal(runs.length,3);
  data=JSON.parse(readFileSync(join(root,'.deving','evidence',runs.find(x=>x!==dir.split('/').at(-1) && JSON.parse(readFileSync(join(root,'.deving','evidence',x,'manifest.json'),'utf8')).mode==='production'),'manifest.json'),'utf8'));
  assert.equal(data.checks.length,4);
  const cfgPath=join(root,'.deving','quality','config.json');
  const cfg=JSON.parse(readFileSync(cfgPath,'utf8'));
  cfg.node.major=24;cfg.node.min_version='24.0.0';cfg.node.max_major_exclusive=25;
  writeFileSync(cfgPath,JSON.stringify(cfg));
  r=tool(...args,'run');
  assert.equal(r.status,1,r.stderr);
  assert.match(r.stdout,/BLOQUEADO/);
  cfg.node.major=22;cfg.node.min_version='22.12.0';cfg.node.max_major_exclusive=23;
  writeFileSync(cfgPath,JSON.stringify(cfg));
  writeFileSync(join(root,'fixtures','e2e.mjs'),"console.log('100 passed\\n5 skipped')\n");
  r=tool(...args,'run');
  assert.equal(r.status,1,r.stderr);
  assert.match(r.stdout,/BLOQUEADO/);
  writeFileSync(join(root,'fixtures','e2e.mjs'),"console.log('100 passed\\n3 skipped')\n");
  // Untracked content modification while status stays unchanged must block.
  writeFileSync(join(root,'fixtures','untracked.txt'),'BEFORE');
  writeFileSync(join(root,'fixtures','build.mjs'),"import fs from 'node:fs'; fs.writeFileSync('fixtures/untracked.txt','AFTER'); console.log('built')\n");
  r=tool(...args,'run');
  assert.equal(r.status,1,r.stderr);
  assert.match(r.stdout,/BLOQUEADO/);
  // Tracked modification also blocks (older logic preserved).
  writeFileSync(join(root,'fixtures','build.mjs'),"import fs from 'node:fs'; fs.writeFileSync('package.json','{}'); console.log('built')\n");
  r=tool(...args,'run');
  assert.equal(r.status,1,r.stderr);
  assert.match(r.stdout,/BLOQUEADO/);
  console.log('SMOKE PASS: preview; conteo JSON Vitest; verificacion hashes logs+JSON; desarrollo/produccion; Node; skips; contenido untracked; diff tracked.');
} finally { rmSync(root,{recursive:true,force:true}); }
